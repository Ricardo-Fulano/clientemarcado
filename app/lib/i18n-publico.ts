const DICIONARIOS: Record<Idioma, Dicionario> = { pt, en, es }

// Sempre devolve um dicionario COMPLETO: qualquer chave que nao exista em en/es
// (ex: uma traducao esquecida no futuro) cai automaticamente no valor em pt.
export function getDicionario(idioma: Idioma): Dicionario {
  if (idioma === 'pt') return pt
  const base = DICIONARIOS[idioma]
  return { ...pt, ...base }
}
