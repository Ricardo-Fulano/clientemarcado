// agendamento publico). NUNCA usar isso pra traduzir conteudo cadastrado pelo cliente
// (nome, bio, titulos de destaque/video, nomes de link/servico/profissional, endereco) -
// esse conteudo sempre permanece exatamente como a pessoa escreveu.
//
// Estrategia de deteccao:
// - Server Component (app/[slug]/page.tsx): le o header "accept-language" via next/headers,
//   sem nenhuma logica no cliente -> zero risco de hidratacao (o HTML enviado ja nasce no
//   idioma certo, cliente nunca precisa "trocar" nada depois).
// - Client Component (app/[slug]/agendar/page.tsx): nao tem acesso a headers() do servidor,
//   entao le navigator.language APOS montar (useEffect) - o render inicial sempre usa 'pt'
//   (o mesmo valor usado no SSR), evitando erro de hidratacao; o idioma correto so aparece
//   uma fracao de segundo depois, o que e o padrao seguro aceito pra deteccao client-side.

export type Idioma = 'pt' | 'en' | 'es'

export function detectarIdiomaHeader(acceptLanguage: string | null | undefined): Idioma {
  if (!acceptLanguage) return 'pt'
  const primeiro = acceptLanguage.split(',')[0]?.trim().toLowerCase() || ''
  if (primeiro.startsWith('en')) return 'en'
  if (primeiro.startsWith('es')) return 'es'
  if (primeiro.startsWith('pt')) return 'pt'
  return 'pt'
}

export function detectarIdiomaNavegador(): Idioma {
  if (typeof navigator === 'undefined') return 'pt'
  const idioma = (navigator.language || 'pt').toLowerCase()
  if (idioma.startsWith('en')) return 'en'
  if (idioma.startsWith('es')) return 'es'
  return 'pt'
}

